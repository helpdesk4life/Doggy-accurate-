// Release signing is read from android/keystore.properties, which is gitignored.
// Without it the release build still assembles, just unsigned, so a fresh clone
// can build and test without a keystore.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.dogwalk"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.dogwalk"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"

        // 10.0.2.2 is the host machine as seen from the Android emulator, and 8443
        // is the Caddy TLS terminator in backend/docker-compose.yml. The debug build
        // trusts Caddy's local CA (src/debug/res/raw/caddy_root.crt), so this works
        // out of the box; a release build needs a real certificate for a real host.
        // Override at runtime from the in-app settings sheet for a physical device.
        buildConfigField("String", "DEFAULT_BACKEND_URL", "\"wss://10.0.2.2:8443/ws/walk\"")
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            isMinifyEnabled = false
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    // The unit tests run on the JVM, where android.util.Log and friends are stubs
    // that throw. Returning defaults lets the classes under test call them without
    // dragging in Robolectric for what is otherwise pure Kotlin.
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}

